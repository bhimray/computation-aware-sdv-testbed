projectRoot = string( ...
    matlab.project.currentProject().RootFolder);

scenarioNames = [
    "aggressive_maneuver", ...
    % "highway_cruise", ...
    % "urban_profile"
    ];
environmentNames = [
    % "dry_road", ...
    "low_friction_road"
    ];
sample_period = "10";

for scenario = scenarioNames
    for environment  = environmentNames
        fprintf("%s and %s performance is plotted.", scenario, environment)
        fixedFile = fullfile( ...
            projectRoot, ...
            "phase4", ...
            "results", ...
            "performance_map_runs", ...
            scenario, ...
            environment, ...
            "sample_time_0" + sample_period + "_ms", ...
            "fixed_mode_run.mat");
        
        
        supervisorFile = fullfile( ...
            projectRoot, ...
            "phase4", ...
            "results", ...
            "lookup_supervisor", ...
            scenario, ...
            environment, ...
            "simulation_output.mat");
        
        outputFile = fullfile( ...
            projectRoot, ...
            "phase4", ...
            "results", ...
            "lookup_supervisor", ...
            scenario, ...
            environment, ...
            "phase4_lookup_supervisor_demo.png");
        
        [demoFigure, demoMetrics] = plot_phase4_demo( ...
            fixedFile, ...
            supervisorFile, ...
            TrackingMetric="lateral", ...
            TimeWindow_s=[NaN, NaN], ...
            env= environment, ...
            scenario = scenario, ...
            FixedLabel="Fixed "+ sample_period +" ms", ...
            SupervisorLabel="Online supervisor", ...
            Title="Fixed "+ sample_period +" ms vs. Online Supervisor", ...
            SaveFile=outputFile);
        
        disp(demoMetrics);
    end
end