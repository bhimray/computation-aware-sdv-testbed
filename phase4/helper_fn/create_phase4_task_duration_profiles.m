function [controlTaskDurationByMode, supervisorTaskDuration, profileInfo] = ...
    create_phase4_task_duration_profiles( ...
        durationBank, stopTime_s, randomSeed, options)
%CREATE_PHASE4_TASK_DURATION_PROFILES Build reproducible scheduler inputs.
%
% controlTaskDurationByMode contains one empirical execution-time stream
% per controller mode. Column order is LOW, MEDIUM, HIGH, corresponding to
% controller modes 1, 2, and 3. The Simulink selector chooses the active
% column online; this function does not know the future active mode.

arguments
    durationBank (1,1) struct
    stopTime_s (1,1) double {mustBePositive}
    randomSeed (1,1) double
    options.SupervisorSampleTime_s (1,1) double ...
        {mustBePositive} = 0.010
    options.SupervisorExecutionTimeSamples_s (:,1) double = zeros(0,1)
    options.SupervisorExecutionTime_s (1,1) double ...
        {mustBeNonnegative} = 0.00005
end

profileTime_s = ...
    (0:options.SupervisorSampleTime_s:stopTime_s).';

modeNames = ["LOW", "MEDIUM", "HIGH"];
controlDuration_s = zeros(numel(profileTime_s), numel(modeNames));

% Use one repeatable random stream per mode. Giving every stream the same
% seed implements common random numbers and makes the HIGH column match a
% fixed-HIGH run that uses the same seed and duration bank.
for modeIndex = 1:numel(modeNames)
    modeName = modeNames(modeIndex);

    assert(isfield(durationBank, modeName), ...
        "Missing %s controller-duration bank.", modeName);

    sourceSamples_s = double( ...
        durationBank.(modeName).samples_s(:));

    valid = isfinite(sourceSamples_s) & sourceSamples_s >= 0;
    sourceSamples_s = sourceSamples_s(valid);

    assert(~isempty(sourceSamples_s), ...
        "%s controller-duration bank has no valid samples.", ...
        modeName);

    randomStream = RandStream( ...
        "mt19937ar", ...
        Seed=randomSeed);

    selectedIndices = randi( ...
        randomStream, ...
        numel(sourceSamples_s), ...
        numel(profileTime_s), ...
        1);

    controlDuration_s(:, modeIndex) = ...
        sourceSamples_s(selectedIndices);
end

controlTaskDurationByMode = timeseries( ...
    controlDuration_s, profileTime_s);
controlTaskDurationByMode.Name = ...
    "phase4_control_task_duration_by_mode";
controlTaskDurationByMode = setinterpmethod( ...
    controlTaskDurationByMode, "zoh");

supervisorSamples_s = double( ...
    options.SupervisorExecutionTimeSamples_s(:));
supervisorSamples_s = supervisorSamples_s( ...
    isfinite(supervisorSamples_s) & supervisorSamples_s >= 0);

if isempty(supervisorSamples_s)
    supervisorDuration_s = repmat( ...
        options.SupervisorExecutionTime_s, ...
        numel(profileTime_s), ...
        1);
    supervisorPolicy = "configured_constant";
else
    supervisorStream = RandStream( ...
        "mt19937ar", ...
        Seed=randomSeed + 1);

    selectedIndices = randi( ...
        supervisorStream, ...
        numel(supervisorSamples_s), ...
        numel(profileTime_s), ...
        1);

    supervisorDuration_s = ...
        supervisorSamples_s(selectedIndices);
    supervisorPolicy = "empirical_profile";
end

supervisorTaskDuration = timeseries( ...
    supervisorDuration_s, profileTime_s);
supervisorTaskDuration.Name = ...
    "phase4_supervisor_task_duration";
supervisorTaskDuration = setinterpmethod( ...
    supervisorTaskDuration, "zoh");

profileInfo = struct( ...
    Time_s=profileTime_s, ...
    ControlDurationByMode_s=controlDuration_s, ...
    SupervisorDuration_s=supervisorDuration_s, ...
    SupervisorPolicy=supervisorPolicy, ...
    RandomSeed=randomSeed);

end
