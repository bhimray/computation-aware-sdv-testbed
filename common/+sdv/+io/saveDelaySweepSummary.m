function files = saveDelaySweepSummary( ...
    summaryTable, ...
    controllerName ...
    )
%SAVEDELAYSWEEPSUMMARY Checkpoint the Phase 1 sweep table.

arguments
    summaryTable table
    controllerName (1,1) string
end

projectRoot = string( ...
    matlab.project.currentProject().RootFolder);

%% all env and scenario will be saved to same table
resultsFolder = fullfile( ...
    projectRoot, ...
    "phase1", ...
    "results", ...
    controllerName, ...
    "constant_delay_sweep" ...
    );

if ~isfolder(resultsFolder)
    mkdir(resultsFolder);
end

files = struct();

files.mat = fullfile( ...
    resultsFolder, ...
    "constant_delay_summary.mat");

files.csv = fullfile( ...
    resultsFolder, ...
    "constant_delay_summary.csv");

save(files.mat, "summaryTable");
writetable(summaryTable, files.csv);

end