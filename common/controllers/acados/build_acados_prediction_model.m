function [model, dynamicsFunction] = ...
    build_acados_prediction_model(parameters)
%BUILD_ACADOS_PREDICTION_MODEL Build the acados dynamic bicycle model.
%
% States:
%   x = [vx; vy; yawRate; lateralError; headingError]
%
% Inputs:
%   u = [frontAxleTorque; roadWheelAngle]
%
% Online parameter:
%   pathCurvature

import casadi.*

%% Symbolic variables

x = SX.sym('x', 5, 1);
xdot = SX.sym('xdot', 5, 1);
u = SX.sym('u', 2, 1);

pathCurvature = ...
    SX.sym('path_curvature', 1, 1);

vx = x(1);
vy = x(2);
yawRate = x(3);
% lateralError = x(4);
headingError = x(5);

frontAxleTorque = u(1);
roadWheelAngle = u(2);

%% Tire slip angles


minimumSpeed = ...
    parameters.minimum_speed_mps;
% vxSafe = fmax(vx, parameters.minimum_speed_mps);
vxSafe = sqrt( ...
    vx^2 + minimumSpeed^2); %% for v=0, Compensator

frontSlipAngle = ...
    atan2( ...
        vy + parameters.lf_m*yawRate, ...
        vxSafe) ...
    - roadWheelAngle;

rearSlipAngle = ...
    atan2( ...
        vy - parameters.lr_m*yawRate, ...
        vxSafe);

frontLateralForce = ...
    -parameters.Cf_Nprad * frontSlipAngle;

rearLateralForce = ...
    -parameters.Cr_Nprad * rearSlipAngle;

%% Longitudinal forces

driveForce = ...
    parameters.drivetrain_efficiency ...
    * frontAxleTorque ...
    / parameters.wheel_radius_m;

resistanceForce = ...
    parameters.rolling_resistance_coefficient ...
    * parameters.mass_kg ...
    * parameters.gravity_mps2 ...
    * tanh( ...
        vx / ...
        parameters.rolling_resistance_smoothing_speed_mps) ...
    + 0.5 ...
    * parameters.air_density_kgpm3 ...
    * parameters.drag_coefficient ...
    * parameters.frontal_area_m2 ...
    * vx ...
    * abs(vx);

%% Nonlinear state equations

vxDot = ...
    vy*yawRate ...
    + ( ...
        driveForce*cos(roadWheelAngle) ...
        - frontLateralForce*sin(roadWheelAngle) ...
        - resistanceForce) ...
    / parameters.mass_kg;

vyDot = ...
    -vx*yawRate ...
    + ( ...
        frontLateralForce*cos(roadWheelAngle) ...
        + rearLateralForce ...
        + driveForce*sin(roadWheelAngle)) ...
    / parameters.mass_kg;

yawRateDot = ...
    ( ...
        parameters.lf_m ...
        * frontLateralForce ...
        * cos(roadWheelAngle) ...
        - parameters.lr_m ...
        * rearLateralForce ...
        + parameters.lf_m ...
        * driveForce ...
        * sin(roadWheelAngle)) ...
    / parameters.yaw_inertia_kgm2;

lateralErrorDot = ...
    vy + vx*headingError;

headingErrorDot = ...
    yawRate - vx*pathCurvature;

explicitDynamics = [
    vxDot
    vyDot
    yawRateDot
    lateralErrorDot
    headingErrorDot
    ];

implicitDynamics = xdot - explicitDynamics;

%% acados model

model = AcadosModel();

model.name = 'sdv_dynamic_bicycle';
model.x = x;
model.xdot = xdot;
model.u = u;
model.p = pathCurvature;

model.f_expl_expr = explicitDynamics;
model.f_impl_expr = implicitDynamics;

%% MATLAB-callable CasADi function for validation

dynamicsFunction = Function( ...
    'sdv_acados_dynamics', ...
    {x, u, pathCurvature}, ...
    {explicitDynamics});

end