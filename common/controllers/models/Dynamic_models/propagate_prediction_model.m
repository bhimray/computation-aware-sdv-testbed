function xNext = ...
    propagate_prediction_model(x,u,kappa,p)
%PROPAGATE_PREDICTION_MODEL
% Propagates the nonlinear prediction model over one controller interval.

numberOfSubsteps = p.integration_substeps;
integrationStep = p.Ts_s/numberOfSubsteps;

xNext = x(:);

for stepIndex = 1:numberOfSubsteps

    k1 = dynamic_model( ...
        xNext,u,kappa,p);

    k2 = dynamic_model( ...
        xNext + 0.5*integrationStep*k1, ...
        u,kappa,p);

    k3 = dynamic_model( ...
        xNext + 0.5*integrationStep*k2, ...
        u,kappa,p);

    k4 = dynamic_model( ...
        xNext + integrationStep*k3, ...
        u,kappa,p);

    xNext = xNext ...
        + integrationStep/6 ...
        * (k1 + 2*k2 + 2*k3 + k4);
end
end