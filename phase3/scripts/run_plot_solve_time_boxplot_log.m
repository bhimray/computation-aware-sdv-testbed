function [solveTimeFigure, solveTimeSummary] = ...
    run_plot_solve_time_boxplot_log()
%RUN_PLOT_SOLVE_TIME_BOXPLOT_LOG Create the paper solve-time comparison.

projectRoot = string( ...
    matlab.project.currentProject().RootFolder);

resultsRoots = [
    fullfile(projectRoot, "phase0", "results", "ACADOS_MPC")
    fullfile(projectRoot, "phase3_20ms", "results", "ACADOS_MPC")
    fullfile(projectRoot, "phase3_50ms", "results", "ACADOS_MPC")
    ];

samplingTimes_ms = [10, 20, 50];

scenarioNames = [ ...
    "urban_profile", ...
    "highway_cruise", ...
    "aggressive_maneuver"];

environmentNames = [ ...
    "dry_road", ...
    "low_friction_road"];

numberOfGroups = ...
    numel(scenarioNames)*numel(environmentNames);

solveTimeGroups_ms = cell( ...
    numberOfGroups, ...
    numel(samplingTimes_ms));

groupLabels = strings(numberOfGroups,1);
groupIndex = 0;

for scenarioIndex = 1:numel(scenarioNames)
    scenarioName = scenarioNames(scenarioIndex);

    for environmentIndex = 1:numel(environmentNames)
        environmentName = environmentNames(environmentIndex);
        groupIndex = groupIndex + 1;

        groupLabels(groupIndex) = ...
            prettyName(scenarioName) + " / " + prettyName(environmentName);

        for periodIndex = 1:numel(samplingTimes_ms)
            resultsFile = fullfile( ...
                resultsRoots(periodIndex), ...
                scenarioName, ...
                environmentName, ...
                scenarioName + "_results.mat");

            solveTimeGroups_ms{groupIndex,periodIndex} = ...
                loadSolveTime_ms(resultsFile);
        end
    end
end

outputFolder = fullfile( ...
    projectRoot, ...
    "phase3", ...
    "results", ...
    "solve_time_comparison");

if ~isfolder(outputFolder)
    mkdir(outputFolder);
end

[solveTimeFigure, solveTimeSummary] = ...
    plot_solve_time_boxplot_log( ...
        solveTimeGroups_ms, ...
        groupLabels, ...
        samplingTimes_ms, ...
        SeriesLabels=["10 ms", "20 ms", "50 ms"], ...
        Colors=[ ...
            0.00, 0.45, 0.74
            0.85, 0.33, 0.10
            0.93, 0.69, 0.13], ...
        ShowDeadlineLines=true, ...
        FontSize_pt=8, ...
        FigureSize_in=[7.16, 3.6], ...
        ExportPDF=fullfile( ...
            outputFolder, ...
            "solve_time_sampling_comparison_log.pdf"), ...
        ExportPNG=fullfile( ...
            outputFolder, ...
            "solve_time_sampling_comparison_log.png"), ...
        ShowFigure=true);

writetable( ...
    solveTimeSummary, ...
    fullfile( ...
        outputFolder, ...
        "solve_time_sampling_summary_log.csv"));

disp(solveTimeSummary);

end


function solveTime_ms = loadSolveTime_ms(resultsFile)

assert(isfile(resultsFile), ...
    "Result file not found: %s", ...
    resultsFile);

savedData = load(resultsFile);

if isfield(savedData,"results")
    results = savedData.results;
elseif isfield(savedData,"runArtifact") && ...
        isfield(savedData.runArtifact,"results")
    results = savedData.runArtifact.results;
else
    results = findResultsStructure(savedData,resultsFile);
end

assert(isfield(results,"solve_time_s"), ...
    "solve_time_s is missing from %s.", ...
    resultsFile);

solveTime_ms = 1e3*double(results.solve_time_s(:));
solveTime_ms = solveTime_ms( ...
    isfinite(solveTime_ms) & solveTime_ms > 0);

assert(~isempty(solveTime_ms), ...
    "No positive finite solve-time samples found in %s.", ...
    resultsFile);

end


function results = findResultsStructure(savedData,resultsFile)

variableNames = fieldnames(savedData);

for variableIndex = 1:numel(variableNames)
    candidate = savedData.(variableNames{variableIndex});

    if isstruct(candidate) && isfield(candidate,"solve_time_s")
        results = candidate;
        return;
    end
end

error( ...
    "No structure containing solve_time_s was found in %s.", ...
    resultsFile);

end


