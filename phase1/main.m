startup_project;

configuration = ...
    build_phase0_configuration("highway_cruise");

controller = configuration.controller;

% Check MATLAB products before attempting dependency installation.
check_runtime_requirements( ...
    controller, ...
    false);

if controller.controller_backend == controller.BACKEND_ACADOS

    [acadosAvailable, ~] = activate_acados(false);

    projectRoot = string( ...
        matlab.project.currentProject().RootFolder);

    solverFile = fullfile( ...
        projectRoot, ...
        "build", ...
        "acados", ...
        "sdv_dynamic_bicycle", ...
        "acados_solver_sfunction_sdv_dynamic_bicycle." ...
        + string(mexext));

    solverAvailable = isfile(solverFile);

    if ~acadosAvailable || ~solverAvailable

        response = input( ...
            [ ...
            "The acados backend is not ready.\n" ...
            "Install acados and generate the S-function now? [y/N]: " ...
            ], ...
            "s");

        continueSetup = any(strcmpi( ...
            strtrim(response), ...
            ["y","yes"]));

        if ~continueSetup
            error( ...
                "SDV:AcadosSetupDeclined", ...
                "acados setup was declined by the user.");
        end

        if ~acadosAvailable
            setup_acados_dependency;
        end

        if ~solverAvailable
            solverFile = s_fun_generation_acados();
        end

        startup_project;

        configuration = ...
            build_phase0_configuration("highway_cruise");

        controller = configuration.controller;
    end
end

check_runtime_requirements(controller);

%% configure the controller
controllerName = ...
    sdv.config.controllerName(controller);

%% Experiment configuration

scenarioNames = [ ...
    % "highway_cruise", ...
    "urban_profile", ...
    "aggressive_maneuver"
    ];

environmentNames = [ ...
    "dry_road", ...
    "low_friction_road"
    ];

delayValues_ms = 0:5:100;

%% total number of simulation
numberOfRuns = ...
    numel(scenarioNames) * ...
    numel(environmentNames) * ...
    numel(delayValues_ms);

%% Output folders

projectRoot = string( ...
    matlab.project.currentProject().RootFolder);

logFolder = fullfile( ...
    projectRoot, ...
    "phase1", ...
    "logs");

summaryFolder = fullfile( ...
    projectRoot, ...
    "phase1", ...
    "results", ...
    controllerName, ...
    "constant_delay_sweep", ...
    "all_environments");

% if there is no logFolder or summaryFolder, make one.
if ~isfolder(logFolder)
    mkdir(logFolder);
end

if ~isfolder(summaryFolder)
    mkdir(summaryFolder);
end

%% Start diary ( to save all the terminal warnings, error or printf).

runTimestamp = string( ...
    datetime("now", Format="yyyyMMdd_HHmmss"));

logFile = fullfile( ...
    logFolder, ...
    "constant_delay_sweep_" + ...
    runTimestamp + ".txt");

diary(logFile);
diary on;

fprintf("\n========================================\n");
fprintf("Phase 1.1 constant-delay sweep\n");
fprintf("========================================\n");
fprintf("Started:       %s\n", string(datetime("now")));
fprintf("Controller:    %s\n", controllerName);
fprintf("Scenarios:     %s\n", strjoin(scenarioNames, ", "));
fprintf("Environments:  %s\n", strjoin(environmentNames, ", "));
fprintf("Delay range:   %.1f to %.1f ms\n", ...
    delayValues_ms(1), delayValues_ms(end));
fprintf("Delay step:    %.1f ms\n", ...
    delayValues_ms(2) - delayValues_ms(1));
fprintf("Total runs:    %d\n", numberOfRuns);
fprintf("Log file:      %s\n", logFile);
fprintf("========================================\n\n");

%% Initialize combined results

delaySweepSummary = table();

%% to graphics placeholder array (preallocate storage for figures)
delaySweepFigures = gobjects( ...
    numel(environmentNames), 1);

combinedMatFile = fullfile( ...
    summaryFolder, ...
    "constant_delay_all_results.mat");

combinedCsvFile = fullfile( ...
    summaryFolder, ...
    "constant_delay_all_results.csv");

%% Run all scenarios and environments

try
    for environmentIndex = 1:numel(environmentNames)

        environmentName = ...
            environmentNames(environmentIndex);
        %% main command to run the simulation
        [environmentSummary, ...
            delaySweepFigures(environmentIndex)] = ...
            run_constant_delay_sweep( ...
                ScenarioNames=scenarioNames, ...
                EnvironmentName=environmentName, ...
                Delay_ms=delayValues_ms);

        if isempty(delaySweepSummary)
            delaySweepSummary = environmentSummary;
        else
            delaySweepSummary = [ ...
                delaySweepSummary; ...
                environmentSummary];
        end
        
        delaySweepSummary = sortrows( ...
            delaySweepSummary, ...
            [ ...
            "environment_name", ...
            "scenario_name", ...
            "delay_ms" ...
            ]);

        % Combined checkpoint after each environment.
        save( ...
            combinedMatFile, ...
            "delaySweepSummary", ...
            "scenarioNames", ...
            "environmentNames", ...
            "delayValues_ms");

        writetable( ...
            delaySweepSummary, ...
            combinedCsvFile);
        
        % for log files
        fprintf( ...
            "\nEnvironment completed: %s\n", ...
            environmentName);

        fprintf( ...
            "Combined completed rows: %d of %d\n", ...
            height(delaySweepSummary), ...
            numberOfRuns);
    end

    %% Final save

    save( ...
        combinedMatFile, ...
        "delaySweepSummary", ...
        "scenarioNames", ...
        "environmentNames", ...
        "delayValues_ms");

    writetable( ...
        delaySweepSummary, ...
        combinedCsvFile);
    
    % return non-zero elements
    completedRuns = nnz( ...
        delaySweepSummary.simulation_completed);

    failedRuns = height(delaySweepSummary) - ...
        completedRuns;

    fprintf("\n========================================\n");
    fprintf("Phase 1.1 sweep completed\n");
    fprintf("========================================\n");
    fprintf("Finished:        %s\n", string(datetime("now")));
    fprintf("Successful runs: %d\n", completedRuns);
    fprintf("Failed runs:     %d\n", failedRuns);
    fprintf("Total rows:      %d\n", ...
        height(delaySweepSummary));
    fprintf("MAT summary:     %s\n", combinedMatFile);
    fprintf("CSV summary:     %s\n", combinedCsvFile);
    fprintf("========================================\n");

    disp(delaySweepSummary);

catch sweepError
    %% Preserve available combined results

    fprintf("\n========================================\n");
    fprintf("Sweep stopped unexpectedly\n");
    fprintf("========================================\n");
    fprintf("Stopped: %s\n", string(datetime("now")));
    fprintf("%s\n", getReport(sweepError, "extended"));

    if ~isempty(delaySweepSummary)
        partialMatFile = fullfile( ...
            summaryFolder, ...
            "constant_delay_partial_results.mat");

        partialCsvFile = fullfile( ...
            summaryFolder, ...
            "constant_delay_partial_results.csv");

        save( ...
            partialMatFile, ...
            "delaySweepSummary", ...
            "scenarioNames", ...
            "environmentNames", ...
            "delayValues_ms");

        writetable( ...
            delaySweepSummary, ...
            partialCsvFile);

        fprintf( ...
            "Partial MAT summary saved: %s\n", ...
            partialMatFile);

        fprintf( ...
            "Partial CSV summary saved: %s\n", ...
            partialCsvFile);
    end

    diary off;
    rethrow(sweepError);
end

diary off;
