function [summaryTable, sweepFigure] = run_constant_delay_sweep(options)
arguments
    % use enum defaults
    options.ScenarioNames (1,:) ScenarioName = [ScenarioName.urban_profile, ScenarioName.aggressive_maneuver, ScenarioName.highway_cruise]
    options.EnvironmentNames (1,:) EnvironmentName = [EnvironmentName.dry_road, EnvironmentName.low_friction_road]
    options.Delay_ms (1,:) double {mustBeNonnegative} = 0:5:100
end

startup_project;

configuration = build_phase0_configuration( ...
    options.ScenarioNames(1));

controllerName = sdv.config.controllerName( ...
    configuration.controller);

summaryTable = table();

for delay_ms = options.Delay_ms

    delay_s = delay_ms * 1e-3;

    for scenarioName = options.ScenarioNames
        % for log file
        fprintf( ...
            "\nScenario: %s, delay: %.1f ms\n", ...
            scenarioName, ...
            delay_ms);
        for environmentName = options.EnvironmentNames

            try
                % as usual run files which run simulink from here
                [results, ~] = run_phase1_baseline( ...
                    scenarioName, ...
                    environmentName, ...
                    delay_s, ...
                    SaveResults=true, ...
                    SaveFigures=true, ... % to save figures
                    ShowFigures=false);    % to show figures looping simulation
    
                newRow = sdv.metrics.createDelaySweepRow( ...
                    scenarioName, ...
                    environmentName, ...
                    delay_s, ...
                    results);
    
            catch simulationError
                % error will be saved in log files
                warning( ...
                    "SDV:DelaySweepRunFailed", ...
                    "Scenario %s failed at %.1f ms:\n%s", ...
                    scenarioName, ...
                    delay_ms, ...
                    simulationError.message);
    
                newRow = sdv.metrics.createDelaySweepRow( ...
                    scenarioName, ...
                    environmentName, ...
                    delay_s, ...
                    struct(), ...
                    Completed=false, ...
                    ErrorIdentifier=string( ...
                        simulationError.identifier), ...
                    ErrorMessage=string( ...
                        simulationError.message));
            end
            % after creating row save it in table
            if isempty(summaryTable)
                summaryTable = newRow;
            else
                summaryTable = [summaryTable; newRow];
            end

            summaryTable = sortrows( ...
                summaryTable, ...
                ["scenario_name", "environment_name", "delay_ms"]);

            % Checkpoint after every simulation.
            sdv.io.saveDelaySweepSummary( ...
                summaryTable, ...
                controllerName ...
                );
        end
    end
end

%% after all delay and scenario simulation finish for one environment (i.e. friction)
sweepFigure = plotDelaySweepMetrics(summaryTable);

projectRoot = string( ...
    matlab.project.currentProject().RootFolder);

figureFolder = fullfile( ...
    projectRoot, ...
    "phase1", ...
    "figures", ...
    controllerName, ...
    "constant_delay_sweep" ...
    );

sdv.io.exportFigure( ...
    sweepFigure, ...
    figureFolder, ...
    "constant_delay_metrics");

end

function figureHandle = plotDelaySweepMetrics(summaryTable)
%PLOTDELAYSWEEPMETRICS Plot per-run metrics against delay tau.

%% check if the enviroment is handled properly
figureHandle = figure( ...
    Name="Phase 1.1 constant-delay sweep", ...
    Color="white");

layout = tiledlayout( ...
    figureHandle, ...
    2, ...
    2, ...
    TileSpacing="compact", ...
    Padding="compact");

scenarioNames = unique( ...
    summaryTable.scenario_name, ...
    "stable");

nexttile(layout);
plotMetric( ...
    summaryTable, scenarioNames, ...
    "lateral_rmse_m");
ylabel("Lateral RMSE (m)");
title("Lateral tracking RMS");
legend(Location="best");
grid on;

nexttile(layout);
plotMetric( ...
    summaryTable, scenarioNames, ...
    "lateral_peak_m");
ylabel("Peak |e_y| (m)");
title("Peak lateral error");
grid on;

nexttile(layout);
%% TODO: change heading error into angle before plotting
plotMetric( ...
    summaryTable, scenarioNames, ...
    "heading_rmse_rad");
ylabel("Heading RMSE (rad)");
title("Heading RMS");
grid on;

nexttile(layout);
plotMetric( ...
    summaryTable, scenarioNames, ...
    "constraint_violation_samples");
ylabel("Violating samples");
title("Constraint-violation count");
grid on;

xlabel(layout, "Constant actuation delay, \tau (ms)");
title(layout, "Phase 1.1: Metrics versus Constant Delay");

end

function plotMetric(summaryTable, scenarioNames, variableName)
% Plot metric for each scenario and environment on a single axes.

hold on;

environmentNames = unique(summaryTable.environment_name, "stable");
styles = enumeration('sdv.plot.plotStyle');
nStyles = numel(styles);
colors = lines(max(1,numel(environmentNames)));

for iEnv = 1:numel(environmentNames)
    env = environmentNames(iEnv);
    styleSpec = styles(mod(iEnv-1, nStyles) + 1).LineSpec;
    color = colors(mod(iEnv-1, size(colors,1)) + 1, :);

    for scenarioName = scenarioNames.'
        selectedRows = ...
            (summaryTable.scenario_name == scenarioName) & ...
            (summaryTable.environment_name == env);

        if ~any(selectedRows)
            continue
        end

        scenarioTable = sortrows( ...
            summaryTable(selectedRows,:), ...
            "delay_ms");

        % Use style from enum and explicit color (color overrides any
        % color in LineSpec)
        plot( ...
            scenarioTable.delay_ms, ...
            scenarioTable.(variableName), ...
            styleSpec, ...
            "Color", color, ...
            "LineWidth", 1.4, ...
            "MarkerSize", 5, ...
            "DisplayName", sprintf("%s — %s", replace(scenarioName,"_"," "), replace(env,"_"," ")));
    end
end

legend(Location="best");
grid on;
hold off;

end
