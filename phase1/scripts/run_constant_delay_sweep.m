function [summaryTable, sweepFigure] = run_constant_delay_sweep(options)
arguments
    options.ScenarioNames (1,:) string ...
        = [sdv.enum.ScenarioName.urban_profile, ...
        sdv.enum.ScenarioName.aggressive_maneuver, ...
        sdv.enum.ScenarioName.highway_cruise]
    options.EnvironmentNames (1,:) string ...
        = [sdv.enum.EnvironmentName.dry_road, ...
        sdv.enum.EnvironmentName.low_friction_road]
    options.Delay_ms (1,:) double {mustBeNonnegative} = 0:5:100
end

startup_project;

configuration = build_phase0_configuration( ...
    options.ScenarioNames(1));

controllerName = sdv.config.controllerName( ...
    configuration.controller);

summaryTable = table();

for delay_ms = options.Delay_ms

    delay_s = delay_ms * 1e-3;

    for scenarioName = options.ScenarioNames
        % for log file
        fprintf( ...
            "\nScenario: %s, delay: %.1f ms\n", ...
            scenarioName, ...
            delay_ms);
        for environmentName = options.EnvironmentNames

            try
                % as usual run files which run simulink from here
                [results, ~] = run_phase1_baseline( ...
                    scenarioName, ...
                    environmentName, ...
                    delay_s, ...
                    SaveResults=true, ...
                    SaveFigures=true, ... % to save figures
                    ShowFigures=false);    % to show figures looping simulation

                newRow = sdv.metrics.createDelaySweepRow( ...
                    scenarioName, ...
                    environmentName, ...
                    delay_s, ...
                    results);

            catch simulationError
                % error will be saved in log files
                warning( ...
                    "SDV:DelaySweepRunFailed", ...
                    "Scenario %s failed at %.1f ms:\n%s", ...
                    scenarioName, ...
                    delay_ms, ...
                    simulationError.message);

                newRow = sdv.metrics.createDelaySweepRow( ...
                    scenarioName, ...
                    environmentName, ...
                    delay_s, ...
                    struct(), ...
                    Completed=false, ...
                    ErrorIdentifier=string( ...
                    simulationError.identifier), ...
                    ErrorMessage=string( ...
                    simulationError.message));
            end
            % after creating row save it in table
            if isempty(summaryTable)
                summaryTable = newRow;
            else
                summaryTable = [summaryTable; newRow];
            end

            summaryTable = sortrows( ...
                summaryTable, ...
                ["scenario_name", "environment_name", "delay_ms"]);

            % Checkpoint after every simulation.
            sdv.io.saveDelaySweepSummary( ...
                summaryTable, ...
                controllerName ...
                );
        end
    end
end

%% after all delay and scenario simulation finish for one environment (i.e. friction)
sweepFigure = plotDelaySweepMetrics(summaryTable);

projectRoot = string( ...
    matlab.project.currentProject().RootFolder);

figureFolder = fullfile( ...
    projectRoot, ...
    "phase1", ...
    "figures", ...
    controllerName, ...
    "constant_delay_sweep" ...
    );

sdv.io.exportFigure( ...
    sweepFigure, ...
    figureFolder, ...
    "constant_delay_metrics");

end

function figureHandle = plotDelaySweepMetrics(summaryTable)
% Plot constant-delay metrics after the complete sweep finishes.

completedTable = summaryTable( ...
    summaryTable.simulation_completed, :);

assert(~isempty(completedTable), ...
    "No completed simulations are available for plotting.");

% Optional: use degrees in the report figure.
completedTable.heading_rmse_deg = ...
    rad2deg(completedTable.heading_rmse_rad);

figureHandle = figure( ...
    Name="Phase 1.1 constant-delay sweep", ...
    Color="white");

layout = tiledlayout( ...
    figureHandle, ...
    3, ...
    1, ...
    TileSpacing="compact", ...
    Padding="compact");

nexttile(layout);
plotMetric(completedTable, "lateral_rmse_m");
ylabel("Lateral RMSE (m)");
title("Lateral Tracking Error");
grid on;

nexttile(layout);
plotMetric(completedTable, "heading_rmse_deg");
ylabel("Heading RMSE (deg)");
title("Heading Tracking Error");
grid on;

nexttile(layout);
plotMetric(completedTable, ...
    "constraint_violation_samples");
ylabel("Number of violating samples");
title("Total Constraint-Violating Samples");
grid on;

xlabel(layout, ...
    "Constant actuation delay, \tau (ms)");

title(layout, ...
    "Phase 1.1: Performance versus Constant Delay");

end
function plotMetric(summaryTable, variableName)
% Plot one sweep metric for every scenario/environment combination.

hold on;

scenarioNames = unique( ...
    summaryTable.scenario_name, ...
    "stable");

environmentNames = unique( ...
    summaryTable.environment_name, ...
    "stable");

colors = lines(numel(scenarioNames));
styles = enumeration("sdv.enum.plotStyle");

for scenarioIndex = 1:numel(scenarioNames)

    scenarioName = scenarioNames(scenarioIndex);

    for environmentIndex = 1:numel(environmentNames)

        environmentName = ...
            environmentNames(environmentIndex);

        selectedRows = ...
            summaryTable.scenario_name == scenarioName & ...
            summaryTable.environment_name == environmentName;

        if ~any(selectedRows)
            continue;
        end

        selectedTable = sortrows( ...
            summaryTable(selectedRows, :), ...
            "delay_ms");

        styleIndex = mod( ...
            environmentIndex - 1, ...
            numel(styles)) + 1;

        plot( ...
            selectedTable.delay_ms, ...
            selectedTable.(variableName), ...
            styles(styleIndex).LineSpec, ...
            Color=colors(scenarioIndex, :), ...
            LineWidth=1.4, ...
            MarkerSize=5, ...
            DisplayName=replace( ...
            scenarioName + " / " + environmentName, ...
            "_", " "));
    end
end

hold off;
grid on;
legend(Location="best");

end